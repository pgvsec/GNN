"""Evaluate GNN predictions on the Drosophila gap gene network.

Loads ground-truth datasets generated by gen_gap_gene_dataset.py and runs
GRNPredictor.predict() (L1 for root SCCs, L3 for forced SCCs) on each case.

Usage (from REPO_ROOT):
  python real_grn/eval_gap_gene.py \\
      --l1_ckpt $SCRATCH/runs/e2e_v10/l1_best.pt \\
      --l3_ckpt $SCRATCH/runs/e2e_v10/l3_best.pt \\
      --data_base /path/to/real_grn_data \\
      --model both \\
      --refine_steps 0        # 0 = pure ML (fp_hd reports raw ML quality)
      --refine_steps 15       # 15 = with Newton refinement

Important metric honesty note:
  --refine_steps 0 : count_exact AND fp_hd are both pure ML.
  --refine_steps >0: count_exact is still pure ML; fp_hd credits Newton refinement.
"""

import argparse
import json
import sys
from pathlib import Path
from types import SimpleNamespace

import numpy as np
import torch

_REPO = Path(__file__).parent.parent
sys.path.insert(0, str(_REPO))

from real_grn.gap_gene_params import AP_POSITIONS, MODEL_A_GENE_NAMES, MODEL_B_GENE_NAMES


# ---------------------------------------------------------------------------
# Metric helpers (mirrors eval_composition2.py)
# ---------------------------------------------------------------------------
def _fp_hd(pred_fps, gt_fps):
    """Fraction of GT fixed points covered within half a log-decade."""
    if len(gt_fps) == 0:
        return float("nan")
    if len(pred_fps) == 0:
        return 0.0
    hits = 0
    for gfp in gt_fps:
        dists = [
            np.max(np.abs(
                np.log10(np.clip(pfp, 1e-12, None)) -
                np.log10(np.clip(gfp, 1e-12, None))
            ))
            for pfp in pred_fps
        ]
        if min(dists) <= 0.5:
            hits += 1
    return hits / len(gt_fps)


def _stable_acc(pred_stab, gt_stab):
    STABLE = {0, 1}
    if len(gt_stab) == 0:
        return float("nan")
    gt_s = sorted([int(s in STABLE) for s in gt_stab])
    pr_s = sorted([int(s in STABLE) for s in pred_stab])
    n = max(len(gt_s), len(pr_s))
    gt_s += [0] * (n - len(gt_s))
    pr_s += [0] * (n - len(pr_s))
    return sum(a == b for a, b in zip(gt_s, pr_s)) / n


# ---------------------------------------------------------------------------
# Load model helpers
# ---------------------------------------------------------------------------
def _load_l1(path, device):
    from model import SccFixedPointNet
    ck = torch.load(path, map_location=device, weights_only=False)
    cfg = SimpleNamespace(**ck["cfg"])
    m = SccFixedPointNet(cfg)
    w = ck.get("ema", ck.get("model"))
    if any(k.startswith("backbone.") for k in w):
        w = {k[len("backbone."):]: v for k, v in w.items() if k.startswith("backbone.")}
    m.load_state_dict(w)
    return m.to(device).eval(), cfg


def _load_l3(path, l1_model, device):
    from model import SccFixedPointNet
    from model_c import CorpusCNet
    ck = torch.load(path, map_location=device, weights_only=False)
    cfg = SimpleNamespace(**ck["cfg"])
    backbone = SccFixedPointNet(cfg)
    m = CorpusCNet(backbone, cfg)
    m.load_state_dict(ck.get("ema", ck.get("model")))
    return m.to(device).eval(), cfg


# ---------------------------------------------------------------------------
# Main evaluation
# ---------------------------------------------------------------------------
def eval_model(model_name, data_base, l1_ckpt, l3_ckpt, refine_steps, device, verbose=True):
    from assemble import GRNPredictor

    gene_names = MODEL_A_GENE_NAMES if model_name == "A" else MODEL_B_GENE_NAMES
    n_genes    = len(gene_names)
    data_dir   = Path(data_base) / f"gap_gene_model_{model_name.lower()}"

    if not data_dir.exists():
        print(f"  Dataset not found: {data_dir}")
        print(f"  Run gen_gap_gene_dataset.py first.")
        return None

    # Load ground truth
    adj_all   = np.load(data_dir / "adj.npy")
    P_all     = np.load(data_dir / "P.npy")
    K_all     = np.load(data_dir / "K.npy")
    T_all     = np.load(data_dir / "T.npy")
    nh_all    = np.load(data_dir / "nh.npy")
    F_all     = np.load(data_dir / "F.npy")
    fp_ptr    = np.load(data_dir / "fp_ptr.npy")
    n_fp_arr  = np.load(data_dir / "n_fp.npy")
    fp_state  = np.load(data_dir / "fp_state.npy")
    fp_stab   = np.load(data_dir / "fp_stab.npy")

    l1_model, _ = _load_l1(l1_ckpt, device)
    l3_model, _ = _load_l3(l3_ckpt, l1_model, device)
    predictor   = GRNPredictor(l1_model, l3_model, device=device, refine_steps=refine_steps)

    model_title = ("Model A — Reinitz/Manu 1-SCC {Hb,Kr,Gt,Kni}"
                   if model_name == "A" else
                   "Model B — Papatsenko-Levine 2-SCC {Hb,Kni}→{Kr,Gt}")
    if verbose:
        print(f"\n{'='*65}")
        print(f"  {model_title}  (refine_steps={refine_steps})")
        print(f"  Genes: {gene_names}")
        print(f"{'='*65}")
        hdr = f"  {'AP pos':<10} {'GT FPs':>6} {'Pred FPs':>8} {'count_exact':>11} {'fp_hd':>7} {'stable_acc':>10}"
        print(hdr)
        print("  " + "-" * (len(hdr) - 2))

    rows = []
    for i, ap_name in enumerate(AP_POSITIONS.keys()):
        adj = adj_all[i]
        P   = P_all[i]
        K   = K_all[i]
        T   = T_all[i]
        nh  = nh_all[i]
        F   = F_all[i]

        fp0, fp1 = int(fp_ptr[i]), int(fp_ptr[i]) + int(n_fp_arr[i])
        gt_states = fp_state[fp0:fp1]
        gt_stabs  = fp_stab[fp0:fp1]
        n_fp_gt   = len(gt_states)

        result = predictor.predict(adj, P, K, T, nh, F)
        # GRNPredictor.predict() returns:
        #   "global_fps"  — raw ML assembled FP coordinates [n_fps, N]
        #   "global_stab" — ML predicted stability class [n_fps]
        #   "fps_refined" — same shape, Newton-refined (identical when refine_steps=0)
        #   "n_fps"       — count from count head (int)
        pred_fps   = result.get("fps_refined", result.get("global_fps", np.zeros((0, n_genes))))
        pred_stabs = result.get("global_stab", np.zeros(0, dtype=np.uint8))
        n_fp_pred  = int(result.get("n_fps", 0))

        count_exact = int(n_fp_pred == n_fp_gt)
        hd          = _fp_hd(pred_fps, gt_states)
        sa          = _stable_acc(pred_stabs, gt_stabs)

        if verbose:
            print(f"  {ap_name:<10} {n_fp_gt:>6} {n_fp_pred:>8} {count_exact:>11} "
                  f"{hd:>7.3f} {sa:>10.3f}")

        rows.append({
            "model": model_name,
            "ap_position": ap_name,
            "n_fp_gt": n_fp_gt,
            "n_fp_pred": n_fp_pred,
            "count_exact": count_exact,
            "fp_hd": hd,
            "stable_acc": sa,
        })

        if verbose:
            # Print predicted fixed points for inspection
            on_cutoff = 0.5  # gene is "ON" if expression > 50% of natural level
            for j, (pfp, ps) in enumerate(zip(pred_fps, pred_stabs)):
                on_pred = [gene_names[k] for k in range(n_genes)
                           if pfp[k] > on_cutoff * P[k] / K[k]]
                print(f"    pred FP{j+1}: "
                      f"ON≈{on_pred}  x={[f'{pfp[k]:.3f}' for k in range(n_genes)]}")
            if n_fp_gt > 0:
                print(f"    ground truth ({n_fp_gt} FPs):")
                for j, (gfp, gs) in enumerate(zip(gt_states, gt_stabs)):
                    on_gt = [gene_names[k] for k in range(n_genes)
                             if gfp[k] > on_cutoff * P[k] / K[k]]
                    print(f"      GT FP{j+1}: ON≈{on_gt}  x={[f'{gfp[k]:.3f}' for k in range(n_genes)]}")

    # Summary
    n = len(rows)
    if n > 0:
        ce = sum(r["count_exact"] for r in rows) / n
        hd_vals = [r["fp_hd"] for r in rows if not np.isnan(r["fp_hd"])]
        sa_vals = [r["stable_acc"] for r in rows if not np.isnan(r["stable_acc"])]
        hd = sum(hd_vals) / len(hd_vals) if hd_vals else float("nan")
        sa = sum(sa_vals) / len(sa_vals) if sa_vals else float("nan")
        if verbose:
            print(f"\n  Mean over {n} AP positions: "
                  f"count_exact={ce:.3f}  fp_hd={hd:.3f}  stable_acc={sa:.3f}")

    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--l1_ckpt",      required=True)
    ap.add_argument("--l3_ckpt",      required=True)
    ap.add_argument("--data_base",    required=True,
                    help="Directory containing gap_gene_model_a/ and gap_gene_model_b/")
    ap.add_argument("--model",        choices=["A", "B", "both"], default="both")
    ap.add_argument("--refine_steps", type=int, default=0,
                    help="Newton refinement steps (0 = pure ML baseline)")
    ap.add_argument("--no_cuda",      action="store_true")
    ap.add_argument("--out_json",     default=None,
                    help="Optional path to save results as JSON")
    args = ap.parse_args()

    device = torch.device(
        "cpu" if args.no_cuda or not torch.cuda.is_available() else "cuda"
    )
    print(f"Device: {device}")
    print(f"L1 checkpoint: {args.l1_ckpt}")
    print(f"L3 checkpoint: {args.l3_ckpt}")
    print(f"Refine steps: {args.refine_steps} "
          f"({'pure ML' if args.refine_steps == 0 else 'ML + Newton'})")

    models = ["A", "B"] if args.model == "both" else [args.model]
    all_rows = []
    for m in models:
        rows = eval_model(m, args.data_base, args.l1_ckpt, args.l3_ckpt,
                          args.refine_steps, device)
        if rows:
            all_rows.extend(rows)

    if args.out_json and all_rows:
        with open(args.out_json, "w") as f:
            json.dump(all_rows, f, indent=2)
        print(f"\nResults saved to {args.out_json}")


if __name__ == "__main__":
    main()
